/**
 * Generates apps/tui/src/theme/github-palettes.ts from @primer/primitives functional theme CSS.
 *
 * Usage: bun scripts/import-primer-themes.ts <dir with dist/css/functional/themes/*.css> <version>
 *
 * The CSS is read as data only. A missing Primer variable is an error, never a silent default.
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {join, resolve} from 'node:path';

const THEMES = [
  ['github-light', 'light', 'Light default', 'light'],
  ['github-light-high-contrast', 'light-high-contrast', 'Light high contrast', 'light'],
  ['github-light-colorblind', 'light-colorblind', 'Light colorblind', 'light'],
  ['github-light-tritanopia', 'light-tritanopia', 'Light tritanopia', 'light'],
  ['github-dark', 'dark', 'Dark default', 'dark'],
  ['github-dark-high-contrast', 'dark-high-contrast', 'Dark high contrast', 'dark'],
  ['github-dark-colorblind', 'dark-colorblind', 'Dark colorblind', 'dark'],
  ['github-dark-tritanopia', 'dark-tritanopia', 'Dark tritanopia', 'dark'],
  ['github-dark-dimmed', 'dark-dimmed', 'Dark dimmed', 'dark'],
] as const;

/** Cosmew token ← Primer functional variable (ADR 0127). */
const MAPPING: Record<string, string> = {
  background: 'bgColor-default',
  backgroundPanel: 'bgColor-muted',
  backgroundElevated: 'overlay-bgColor',
  foreground: 'fgColor-default',
  foregroundMuted: 'fgColor-muted',
  foregroundSubtle: 'fgColor-muted',
  accent: 'fgColor-accent',
  accentForeground: 'fgColor-onEmphasis',
  border: 'borderColor-default',
  borderFocused: 'focus-outlineColor',
  selection: 'bgColor-accent-muted',
  selectionForeground: 'fgColor-default',
  cursor: 'fgColor-accent',
  error: 'fgColor-danger',
  warning: 'fgColor-attention',
  success: 'fgColor-success',
  info: 'fgColor-accent',
  diffAdded: 'fgColor-success',
  diffRemoved: 'fgColor-danger',
  diffContext: 'fgColor-muted',
  syntaxKeyword: 'color-prettylights-syntax-keyword',
  syntaxString: 'color-prettylights-syntax-string',
  syntaxComment: 'color-prettylights-syntax-comment',
  syntaxFunction: 'color-prettylights-syntax-entity',
  markdownHeading: 'fgColor-accent',
  markdownCode: 'color-prettylights-syntax-constant',
  scrollbar: 'borderColor-muted',
  composerBackground: 'bgColor-muted',
  sidebarBackground: 'bgColor-inset',
  overlayBackground: 'overlay-bgColor',
};

export function parseVariables(css: string): Map<string, string> {
  const vars = new Map<string, string>();
  for (const match of css.matchAll(/--([A-Za-z0-9-]+):\s*([^;]+);/g)) {
    if (!vars.has(match[1]!)) vars.set(match[1]!, match[2]!.trim());
  }
  return vars;
}

export function resolveVariable(vars: Map<string, string>, name: string, seen = new Set<string>()): string {
  if (seen.has(name)) throw new Error(`Cyclic Primer variable --${name}`);
  seen.add(name);
  const value = vars.get(name);
  if (value === undefined) throw new Error(`Missing Primer variable --${name}`);
  const ref = /^var\(--([A-Za-z0-9-]+)\)$/.exec(value);
  return ref ? resolveVariable(vars, ref[1]!, seen) : value;
}

/** Flattens #rgb, #rrggbb or #rrggbbaa over an opaque background. */
export function flattenHex(value: string, background: string): string {
  let hex = value.toLowerCase().replace(/^#/, '');
  if (!/^[0-9a-f]+$/.test(hex) || ![3, 6, 8].includes(hex.length)) throw new Error(`Unsupported colour ${value}`);
  if (hex.length === 3) hex = [...hex].map(c => c + c).join('');
  if (hex.length === 6) return `#${hex}`;
  const alpha = parseInt(hex.slice(6, 8), 16) / 255;
  const bg = background.replace(/^#/, '');
  const out = [0, 2, 4].map(i => {
    const fg = parseInt(hex.slice(i, i + 2), 16);
    const back = parseInt(bg.slice(i, i + 2), 16);
    return Math.round(fg * alpha + back * (1 - alpha))
      .toString(16)
      .padStart(2, '0');
  });
  return `#${out.join('')}`;
}

function main(): void {
  const [dir, version] = process.argv.slice(2);
  if (!dir || !version) throw new Error('usage: bun scripts/import-primer-themes.ts <cssDir> <version>');
  const entries = THEMES.map(([id, file, name, mode]) => {
    const vars = parseVariables(readFileSync(join(resolve(dir), `${file}.css`), 'utf8'));
    const background = flattenHex(resolveVariable(vars, 'bgColor-default'), '#000000');
    const tokens = Object.fromEntries(
      Object.entries(MAPPING).map(([token, variable]) => [
        token,
        flattenHex(resolveVariable(vars, variable), background),
      ]),
    );
    return {id, name, mode, tokens};
  });
  const body = entries
    .map(
      e =>
        `  '${e.id}': {\n    name: '${e.name}',\n    mode: '${e.mode}',\n    tokens: ${JSON.stringify(e.tokens, null, 6).replace(/\n}$/, '\n    }')},\n  },`,
    )
    .join('\n');
  const source = `// Generated by scripts/import-primer-themes.ts from @primer/primitives ${version} (MIT). Do not edit.
import type {ThemeTokens} from '@cosmew/contracts';

export const PRIMER_SOURCE = {package: '@primer/primitives', version: '${version}', accessed: '2026-11-28'} as const;

export const GITHUB_THEME_IDS = ${JSON.stringify(THEMES.map(t => t[0]))} as const;
export type GithubThemeId = (typeof GITHUB_THEME_IDS)[number];

export const GITHUB_PALETTES: Readonly<
  Record<GithubThemeId, {readonly name: string; readonly mode: 'light' | 'dark'; readonly tokens: ThemeTokens}>
> = {
${body}
};
`;
  writeFileSync(resolve(import.meta.dir, '../apps/tui/src/theme/github-palettes.ts'), source);
}

if (import.meta.main) main();
